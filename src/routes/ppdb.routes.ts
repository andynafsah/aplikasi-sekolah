import { Router } from 'express';
import { PpdbController } from '../controllers/ppdb.controller';
import { verifyJWT } from '../../server';

export const ppdbRoutes = Router();
const controller = new PpdbController();

ppdbRoutes.post('/getAdmissionSettings', (req, res, next) => {
  const token = req.headers.authorization?.split(' ')[1] || req.body.token;
  const authUser = token ? verifyJWT(token) : null;
  const tenantId = authUser ? authUser.tenant_id : req.body.tenant_id;
  const username = authUser ? authUser.username : '';
  const role = authUser ? authUser.role : '';
  controller.handle('getAdmissionSettings', req, res, tenantId, authUser, username, role);
});
